// Generates lib/database.types.ts from the hosted Supabase project, without the Supabase CLI.
//
//   pnpm -C apps/web db:types
//
// Needs SUPABASE_URL (project ref is taken from its hostname) and SUPABASE_ACCESS_TOKEN, a personal access
// token from https://supabase.com/dashboard/account/tokens (NOT the service role key). Values come from
// apps/web/.env.local or the environment.
//
// It calls the Supabase Management API `GET /v1/projects/{ref}/types/typescript`. That endpoint is what the
// CLI uses, but it has NOT been exercised from this repo. If it fails the existing hand-written
// lib/database.types.ts is left untouched.
import { existsSync, renameSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const envFile = resolve(process.cwd(), ".env.local");
if (existsSync(envFile)) process.loadEnvFile(envFile);

const url = process.env.SUPABASE_URL;
const token = process.env.SUPABASE_ACCESS_TOKEN;
if (!url || !token) {
  console.error("Set SUPABASE_URL and SUPABASE_ACCESS_TOKEN (personal access token) in apps/web/.env.local.");
  process.exit(1);
}

const ref = new URL(url).hostname.split(".")[0];
const endpoint = `https://api.supabase.com/v1/projects/${ref}/types/typescript?included_schemas=public`;

const res = await fetch(endpoint, { headers: { Authorization: `Bearer ${token}` } });
if (!res.ok) {
  console.error(`Type generation failed: HTTP ${res.status} ${await res.text()}`);
  console.error("lib/database.types.ts was not changed.");
  process.exit(1);
}
const body = await res.json();
if (typeof body?.types !== "string" || !body.types.includes("export type Database")) {
  console.error("Unexpected response shape; lib/database.types.ts was not changed.");
  process.exit(1);
}

const helpers = `
export type Tables<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Row"];
export type TablesInsert<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Update"];
export type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];
`;

const out = resolve(process.cwd(), "lib/database.types.ts");
const tmp = `${out}.tmp`;
writeFileSync(tmp, `/* Generated by scripts/db-types.mjs from the hosted project. Do not edit. */\n${body.types}\n${helpers}`);
renameSync(tmp, out);
console.log(`Wrote ${out}`);
